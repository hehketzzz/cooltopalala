// GDR v1 replay writer (https://github.com/maxnut/GDReplayFormat, branch gdr1).
// Mega Hack v9 reads GDR replays from "<Geometry Dash folder>/replays".
// The same document is written either as msgpack (.gdr) or JSON (.gdr.json).

#include "Macro.hpp"
