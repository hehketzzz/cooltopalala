ExportResult exportMacro(Info const& info, std::vector<Input> const& inputs,
                         std::filesystem::path const& dir, std::string const& format) {
    ExportResult res;

    JsonWriter json;
    writeReplay(json, info, inputs);
    MsgpackWriter msgpack;
    writeReplay(msgpack, info, inputs);

    bool wantBinary = format == "gdr" || format == "both";
    bool wantJson = format == "gdr.json" || format == "both" || (!wantBinary);

    auto base = safeFileName(info.levelName) + "_pathfinder";

    auto writeTo = [&](std::filesystem::path const& folder, bool report) {
        std::string err;
        if (wantBinary) {
            auto p = folder / (base + ".gdr");
            if (writeFile(p, msgpack.out.data(), msgpack.out.size(), err)) { if (report) res.files.push_back(p); }
            else if (report) res.errors.push_back(err);
        }
        if (wantJson) {
            auto p = folder / (base + ".gdr.json");
            if (writeFile(p, json.out.data(), json.out.size(), err)) { if (report) res.files.push_back(p); }
            else if (report) res.errors.push_back(err);
        }
    };

    writeTo(dir, true);
    // backup copy, so a macro is never lost if the game folder is not writable
    auto backup = Mod::get()->getSaveDir() / "replays";
    if (res.files.empty()) writeTo(backup, true);
    else writeTo(backup, false);

    return res;
}

